import { z } from 'zod';
import {
  CircuitType,
  CombBusbarConfig,
  ComponentCategory,
  CurveType,
  GroundingSystem,
  LayoutTopology,
  PanelConfig,
  PanelModule,
  PhaseAssignment,
  RailId,
  SupplyType,
  VoltageSystem,
  WireConnection,
  WireType,
} from '../types/panel';

export const ComponentCategorySchema: z.ZodType<ComponentCategory> = z.enum([
  'main_breaker',
  'idr',
  'rcbo',
  'dps',
  'breaker',
]);

export const PhaseAssignmentSchema: z.ZodType<PhaseAssignment> = z.enum([
  'R',
  'S',
  'T',
  'RS',
  'RT',
  'ST',
  'RST',
  'N',
  'PE',
]);

export const CircuitTypeSchema: z.ZodType<CircuitType> = z.enum([
  'lighting',
  'tug',
  'tue',
  'protection',
]);

export const CurveTypeSchema: z.ZodType<CurveType> = z.enum(['B', 'C', 'D']);

export const WireTypeSchema: z.ZodType<WireType> = z.enum([
  'phase_r',
  'phase_s',
  'phase_t',
  'neutral',
  'ground',
]);

export const RailIdSchema: z.ZodType<RailId> = z.enum([
  'top_main',
  'left_rail',
  'right_rail',
  'row_1',
  'row_2',
  'row_3',
  'row_4',
]);

export const LayoutTopologySchema: z.ZodType<LayoutTopology> = z.enum(
  ['fishbone', 'horizontal'],
  {
    error: 'Topologia deve ser "fishbone" ou "horizontal"',
  }
);

export const SupplyTypeSchema: z.ZodType<SupplyType> = z.enum(
  ['mono', 'bi', 'tri'],
  {
    error: 'Tipo de fornecimento deve ser "mono", "bi" ou "tri"',
  }
);

export const VoltageSystemSchema: z.ZodType<VoltageSystem> = z.enum(
  ['127_220', '220_380'],
  {
    error: 'Sistema de tensão deve ser "127_220" ou "220_380"',
  }
);

export const GroundingSystemSchema: z.ZodType<GroundingSystem> = z.enum(
  ['TN-S', 'TN-C-S', 'TN-C', 'TT', 'IT'],
  {
    error: 'Esquema de aterramento deve ser "TN-S", "TN-C-S", "TN-C", "TT" ou "IT"',
  }
);

export const ModulePolesSchema = z.preprocess(
  (val) => (typeof val === 'string' && val.trim() !== '' ? Number(val) : val),
  z.union([z.literal(1), z.literal(2), z.literal(3), z.literal(4)], {
    error: 'Número de polos deve ser 1, 2, 3 ou 4',
  })
);

export const WireGaugeSchema = z.preprocess(
  (val) => (typeof val === 'string' && val.trim() !== '' ? Number(val) : val),
  z
    .number({ error: 'Bitola do condutor deve ser um número' })
    .positive('Bitola do condutor deve ser maior que zero')
);

export const VoltageSchema = z.preprocess(
  (val) => (typeof val === 'string' && val.trim() !== '' ? Number(val) : val),
  z.union([z.literal(127), z.literal(220), z.literal(380)], {
    error: 'Tensão deve ser 127V, 220V ou 380V',
  })
);

export const RatingAmpsSchema = z.preprocess(
  (val) => (typeof val === 'string' && val.trim() !== '' ? Number(val) : val),
  z
    .number({ error: 'Corrente nominal deve ser um número' })
    .positive('Corrente nominal deve ser maior que zero')
);

export const PowerWattsSchema = z.preprocess(
  (val) => (typeof val === 'string' && val.trim() !== '' ? Number(val) : val),
  z
    .number({ error: 'Potência deve ser um número' })
    .min(0, 'Potência não pode ser negativa')
);

export const PanelModuleSchema = z.object({
  id: z.string().default(() => `mod-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`),
  category: ComponentCategorySchema,
  name: z.string().default('Circuito'),
  circuitNumber: z.number().int().positive().optional(),
  room: z.string().optional(),
  circuitType: CircuitTypeSchema.default('tug'),
  poles: ModulePolesSchema,
  ratingAmps: RatingAmpsSchema.default(20),
  curve: CurveTypeSchema.optional(),
  sensitivityMa: z.number().positive().optional(),
  dpsKa: z.number().positive().optional(),
  dpsVoltage: z.number().positive().optional(),
  railId: RailIdSchema,
  position: z.number().int().min(0).default(0),
  phases: PhaseAssignmentSchema.default('R'),
  voltage: VoltageSchema.default(127),
  powerWatts: PowerWattsSchema.default(0),
  wireGaugeMm2: WireGaugeSchema,
  isOn: z.boolean().default(true),
  drProtected: z.boolean().optional().default(false),
  idrId: z.string().optional(),
  notes: z.string().optional(),
  lengthMeters: z.number().positive().optional(),
  powerFactor: z.number().positive().optional(),
  groupingFactor: z.number().positive().optional(),
  groupingCircuitsCount: z.number().int().positive().optional(),
});

export const WireConnectionSchema = z.object({
  id: z.string().default(() => `wire-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`),
  fromId: z.string(),
  fromPort: z.string(),
  toId: z.string(),
  toPort: z.string(),
  wireType: WireTypeSchema,
  gaugeMm2: WireGaugeSchema,
  customColor: z.string().optional(),
  label: z.string().optional(),
  isAutoGenerated: z.boolean().optional().default(false),
});

export const CombBusbarConfigSchema = z.object({
  id: z.string().default(() => `comb-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`),
  railId: RailIdSchema,
  type: z.enum(['mono', 'bi', 'tri']),
  startSlot: z.number().int().min(0).default(0),
  endSlot: z.number().int().min(0).default(0),
  hasGenericConnectors: z.boolean().default(false),
});

export const PanelConfigSchema = z.object({
  id: z.string().default('qdc-project'),
  title: z.string().default('Quadro de Distribuição'),
  subtitle: z.string().default('Planejamento e Dimensionamento NBR 5410'),
  topology: LayoutTopologySchema,
  supplyType: SupplyTypeSchema.default('tri'),
  voltageSystem: VoltageSystemSchema.default('127_220'),
  groundingSystem: GroundingSystemSchema.default('TN-S'),
  penGroundedAtPanel: z.boolean().optional().default(true),
  fishboneSlotsPerSide: z.number().int().min(6).default(12),
  horizontalRows: z.number().int().min(1).max(6).default(3),
  modulesPerRow: z.number().int().min(4).max(36).default(16),
  wireRoutingStyle: z.enum(['bundled', 'curved']).default('curved'),
  showWires: z.boolean().default(true),
  wireFilter: z.enum(['all', 'phases', 'neutral', 'ground']).default('all'),
  phaseColorScheme: z.enum(['nbr_modern', 'classic_br']).default('nbr_modern'),
  modules: z.array(PanelModuleSchema).default([]),
  wires: z.array(WireConnectionSchema).default([]),
  combBusbars: z.array(CombBusbarConfigSchema).default([]),
});

export type PanelModuleInput = z.input<typeof PanelModuleSchema>;
export type PanelModuleOutput = z.output<typeof PanelModuleSchema>;
export type WireConnectionInput = z.input<typeof WireConnectionSchema>;
export type CombBusbarConfigInput = z.input<typeof CombBusbarConfigSchema>;
export type PanelConfigInput = z.input<typeof PanelConfigSchema>;
export type PanelConfigOutput = z.output<typeof PanelConfigSchema>;

export type ParsePanelConfigResult =
  | { success: true; data: PanelConfig }
  | { success: false; errors: string[] };

/**
 * Validates and sanitizes raw JSON or object input against the PanelConfig schema.
 * Returns parsed PanelConfig with sensible defaults or list of descriptive validation error messages.
 */
export function parsePanelConfig(rawJson: unknown): ParsePanelConfigResult {
  let target: unknown = rawJson;
  if (typeof rawJson === 'string') {
    try {
      target = JSON.parse(rawJson);
    } catch {
      return {
        success: false,
        errors: ['Erro de sintaxe JSON: o texto fornecido não é um JSON válido.'],
      };
    }
  }

  if (!target || typeof target !== 'object' || Array.isArray(target)) {
    return {
      success: false,
      errors: ['O arquivo fornecido não é um objeto JSON válido.'],
    };
  }

  const result = PanelConfigSchema.safeParse(target);
  if (!result.success) {
    const errors = result.error.issues.map((issue) => {
      const path = issue.path.length > 0 ? issue.path.join('.') : 'root';
      return `[${path}]: ${issue.message}`;
    });
    return {
      success: false,
      errors,
    };
  }

  return {
    success: true,
    data: result.data as PanelConfig,
  };
}
