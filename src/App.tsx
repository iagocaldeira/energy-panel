type ActiveTab = 'canvas' | 'unifilar' | 'schedule' | 'bom';

const STORAGE_KEY = 'qdc_studio_saved_config_v3';

export function App() {
  const [config, setConfig] = useState<PanelConfig>(() => {
    try {
      const saved = localStorage.getItem(STORAGE_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        const validated = parsePanelConfig(parsed);
        if (validated.success) {
          return validated.data;
        }
      }
    } catch {
      // ignore storage errors
    }
    return PANEL_PRESETS.fishbone;
  });

  const [activeTab, setActiveTab] = useState<ActiveTab>('canvas');
  const [selectedModuleId, setSelectedModuleId] = useState<string | null>(null);
  const [wireToolActive, setWireToolActive] = useState<boolean>(false);
  const [activeWireType, setActiveWireType] = useState<WireType>('phase_r');
  const [activeWireGauge, setActiveWireGauge] = useState<number>(2.5);
  const [balancePreview, setBalancePreview] =
    useState<PhaseBalancePreview | null>(null);
  const [breakerPreview, setBreakerPreview] =
    useState<BreakerRecalculatePreview | null>(null);

  // Responsive mobile states
  const [mobileCatalogOpen, setMobileCatalogOpen] = useState<boolean>(false);
  const [mobileInspectorOpen, setMobileInspectorOpen] = useState<boolean>(false);
  const [mobileMenuOpen, setMobileMenuOpen] = useState<boolean>(false);

  const handleSelectModule = (id: string | null) => {
    setSelectedModuleId(id);
  };

  const svgRef = useRef<SVGSVGElement>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);

  useEffect(() => {
    try {
      localStorage.setItem(STORAGE_KEY, JSON.stringify(config));
    } catch {
      // ignore storage errors
    }
  }, [config]);

  const selectedModule =
    config.modules.find((m) => m.id === selectedModuleId) || null;

  const getMaxSlotsForRail = (railId: RailId, cfg: PanelConfig): number => {
    if (railId === 'top_main') return 12;
    if (railId === 'left_rail' || railId === 'right_rail') {
      return cfg.fishboneSlotsPerSide;
    }
    return cfg.modulesPerRow;
  };

  // Helper: regenerate automatic wires only if the panel currently uses auto-wires,
  // ALWAYS preserving manually inserted wires (!w.isAutoGenerated)
  const mergeAutoWithManualWires = (cfg: PanelConfig) => {
    const manualWires = cfg.wires.filter((w) => !w.isAutoGenerated);
    const autoWires = generateAutomaticWires(cfg);
    // Avoid auto-wiring a module port that the user already wired manually
    const manualEndpoints = new Set<string>();
    manualWires.forEach((mw) => {
      manualEndpoints.add(`${mw.fromId}:${mw.fromPort}`);
      manualEndpoints.add(`${mw.toId}:${mw.toPort}`);
    });
    const filteredAuto = autoWires.filter(
      (aw) =>
        !manualEndpoints.has(`${aw.fromId}:${aw.fromPort}`) &&
        !manualEndpoints.has(`${aw.toId}:${aw.toPort}`)
    );
    return [...manualWires, ...filteredAuto];
  };

  const syncWires = (next: PanelConfig, prev: PanelConfig): WireConnection[] => {
    const hadAutoWires = prev.wires.some((w) => w.isAutoGenerated);
    if (!hadAutoWires) {
      const activeModIds = new Set(next.modules.map((m) => m.id));
      return prev.wires.filter(
        (w) =>
          !w.isAutoGenerated &&
          (w.fromId.includes('_') || activeModIds.has(w.fromId)) &&
          (w.toId.includes('_') || activeModIds.has(w.toId))
      );
    }
    return mergeAutoWithManualWires(next);
  };

  // Switch between the 2 models: Espinha de Peixe vs DIN Horizontal
  const handleSwitchTopology = (topology: LayoutTopology) => {
    setConfig((prev) => {
      if (prev.topology === topology) return prev;
      const next: PanelConfig = {
        ...prev,
        topology,
        title:
          topology === 'fishbone'
            ? 'Quadro Espinha de Peixe'
            : 'Quadro DIN Horizontal',
      };

      if (topology === 'fishbone') {
        let leftPos = 0;
        let rightPos = 0;
        let topPos = 0;
        next.modules = prev.modules.map((m) => {
          if (m.category !== 'breaker' && m.category !== 'rcbo') {
            const pos = topPos;
            topPos += m.poles;
            if (m.category === 'main_breaker') topPos += 1; // 1-slot gap after main breaker
            return { ...m, railId: 'top_main', position: pos };
          }
          if (m.poles >= 2 || leftPos + m.poles > next.fishboneSlotsPerSide) {
            const pos = rightPos;
            rightPos += m.poles;
            return { ...m, railId: 'right_rail', position: pos };
          } else {
            const pos = leftPos;
            leftPos += m.poles;
            return { ...m, railId: 'left_rail', position: pos };
          }
        });
      } else {
        let r1Pos = 0;
        let r2Pos = 0;
        let r3Pos = 0;
        next.modules = prev.modules.map((m) => {
          if (m.category !== 'breaker' && m.category !== 'rcbo') {
            const pos = r1Pos;
            r1Pos += m.poles;
            if (m.category === 'main_breaker') r1Pos += 1;
            return { ...m, railId: 'row_1', position: pos };
          }
          if (r2Pos + m.poles <= next.modulesPerRow) {
            const pos = r2Pos;
            r2Pos += m.poles;
            return { ...m, railId: 'row_2', position: pos };
          } else {
            const pos = r3Pos;
            r3Pos += m.poles;
            return { ...m, railId: 'row_3', position: pos };
          }
        });
      }

      next.wires = syncWires(next, prev);
      return next;
    });
  };

  const handleUpdateConfig = (partial: Partial<PanelConfig>) => {
    if (partial.topology && partial.topology !== config.topology) {
      handleSwitchTopology(partial.topology);
      return;
    }
    setConfig((prev) => {
      const next = { ...prev, ...partial };

      // Se mudou supplyType (mono / bi / tri)
      if (partial.supplyType && partial.supplyType !== prev.supplyType) {
        const newSupply = partial.supplyType;
        const is220_380 = next.voltageSystem === '220_380';
        next.modules = next.modules.map((m) => {
          if (m.category === 'main_breaker') {
            const poles = newSupply === 'mono' ? 1 : newSupply === 'bi' ? 2 : 3;
            const phases: PhaseAssignment =
              newSupply === 'mono' ? 'R' : newSupply === 'bi' ? 'RS' : 'RST';
            return { ...m, poles, phases };
          }
          if (m.category === 'idr') {
            const poles = newSupply === 'mono' ? 2 : newSupply === 'bi' ? 2 : 4;
            const phases: PhaseAssignment =
              newSupply === 'mono' ? 'R' : newSupply === 'bi' ? 'RS' : 'RST';
            return { ...m, poles, phases };
          }
          if (m.category === 'dps') {
            if (newSupply === 'mono' && (m.phases === 'S' || m.phases === 'T')) {
              return { ...m, phases: 'R' as PhaseAssignment };
            }
            if (newSupply === 'bi' && m.phases === 'T') {
              return { ...m, phases: 'S' as PhaseAssignment };
            }
            return m;
          }
          if (m.category === 'breaker' || m.category === 'rcbo') {
            if (newSupply === 'mono') {
              return {
                ...m,
                poles: 1,
                phases: 'R' as PhaseAssignment,
                voltage: is220_380 ? 220 : 127,
              };
            }
            if (newSupply === 'bi') {
              if (m.poles >= 3) {
                return {
                  ...m,
                  poles: 2,
                  phases: 'RS' as PhaseAssignment,
                  voltage: is220_380 ? 380 : 220,
                };
              }
              if (m.poles === 1 && m.phases === 'T') {
                return { ...m, phases: 'R' as PhaseAssignment };
              }
              if (m.poles === 2 && m.phases !== 'RS') {
                return { ...m, phases: 'RS' as PhaseAssignment };
              }
            }
          }
          return m;
        });
      }

      // Se mudou voltageSystem (127_220 <-> 220_380)
      if (partial.voltageSystem && partial.voltageSystem !== prev.voltageSystem) {
        const is220_380 = partial.voltageSystem === '220_380';
        next.modules = next.modules.map((m) => {
          if (m.category === 'breaker' || m.category === 'rcbo') {
            const voltage = m.poles === 1 ? (is220_380 ? 220 : 127) : (is220_380 ? 380 : 220);
            return { ...m, voltage };
          }
          return m;
        });
      }

      next.wires = syncWires(next, prev);
      return next;
    });
  };

  // Restore default example for the current topology
  const handleResetToDefaultModel = () => {
    const preset = PANEL_PRESETS[config.topology];
    setConfig(JSON.parse(JSON.stringify(preset)));
    setSelectedModuleId(null);
  };

  // Clear all circuits to build from scratch
  const handleClearPanel = () => {
    setConfig((prev) => ({
      ...prev,
      modules: [],
      wires: [],
    }));
    setSelectedModuleId(null);
  };

  // Clear all wires (manual & automatic)
  const handleClearWires = () => {
    setConfig((prev) => ({
      ...prev,
      wires: [],
    }));
  };

  // Explicitly generate automatic wires while keeping manual wires intact
  const handleAutoWire = () => {
    setConfig((prev) => ({
      ...prev,
      wires: mergeAutoWithManualWires(prev),
      showWires: true,
    }));
  };

  // Find first free slot on a rail
  const findFirstFreeSlot = (
    railId: RailId,
    poles: number,
    modules: PanelModule[],
    maxSlots: number
  ): number | null => {
    const occupied = new Set<number>();
    modules
      .filter((m) => m.railId === railId)
      .forEach((m) => {
        for (let p = 0; p < m.poles; p++) {
          occupied.add(m.position + p);
        }
      });

    for (let slot = 0; slot <= maxSlots - poles; slot++) {
      let fits = true;
      for (let p = 0; p < poles; p++) {
        if (occupied.has(slot + p)) {
          fits = false;
          break;
        }
      }
      if (fits) return slot;
    }
    return null;
  };

  // Create a PanelModule from a catalog key
  const createModuleFromCatalog = (
    catalogKey: string,
    targetRail: RailId,
    targetSlot: number,
    existingModules: PanelModule[],
    supplyType: PanelConfig['supplyType'],
    voltageSystem: PanelConfig['voltageSystem']
  ): PanelModule | null => {
    const tpl = CATALOG_ITEMS.find((c) => c.key === catalogKey);
    if (!tpl) return null;

    const isCircuit = isLoadCircuit(tpl as any);
    const maxCkt = existingModules
      .filter(isLoadCircuit)
      .reduce((max, m) => Math.max(max, m.circuitNumber || 0), 0);

    const nextCktNumber = isCircuit ? maxCkt + 1 : undefined;

    let defaultPhases: PhaseAssignment;
    if (tpl.category === 'dps') {
      const dpsOrder: PhaseAssignment[] =
        supplyType === 'tri'
          ? ['R', 'S', 'T', 'N']
          : supplyType === 'bi'
          ? ['R', 'S', 'N']
          : ['R', 'N'];
      const existingDpsPhases = new Set(
        existingModules.filter((m) => m.category === 'dps').map((m) => m.phases)
      );
      defaultPhases =
        dpsOrder.find((p) => !existingDpsPhases.has(p)) ||
        dpsOrder[
          existingModules.filter((m) => m.category === 'dps').length %
            dpsOrder.length
        ];
    } else if (tpl.poles === 1) {
      const available1P: PhaseAssignment[] =
        supplyType === 'tri'
          ? ['R', 'S', 'T']
          : supplyType === 'bi'
          ? ['R', 'S']
          : ['R'];
      defaultPhases = available1P[maxCkt % available1P.length];
    } else if (tpl.poles === 2) {
      defaultPhases = 'RS';
    } else {
      defaultPhases = 'RST';
    }

    const is220_380 = voltageSystem === '220_380';
    const defaultVolt: 127 | 220 | 380 =
      tpl.poles === 1 ? (is220_380 ? 220 : 127) : (is220_380 ? 380 : 220);

    // Link breaker to first sectoral IDR if available
    const firstIdr = existingModules.find((m) => m.category === 'idr');

    return {
      id: `mod-${Date.now()}-${Math.random().toString(36).slice(2, 6)}`,
      category: tpl.category,
      name:
        isCircuit
          ? `${tpl.defaultName} ${nextCktNumber}`
          : tpl.defaultName,
      circuitNumber: nextCktNumber,
      room: isCircuit ? 'Geral' : undefined,
      circuitType: tpl.circuitType,
      poles: tpl.poles,
      ratingAmps: tpl.ratingAmps,
      curve: tpl.curve || 'C',
      sensitivityMa: tpl.category === 'idr' || tpl.category === 'rcbo' ? (tpl.sensitivityMa || 30) : undefined,
      dpsKa: tpl.category === 'dps' ? 20 : undefined,
      dpsVoltage: tpl.category === 'dps' ? 275 : undefined,
      railId: targetRail,
      position: targetSlot,
      phases: defaultPhases,
      voltage: defaultVolt,
      powerWatts: tpl.powerWatts,
      wireGaugeMm2: tpl.wireGaugeMm2,
      isOn: true,
      drProtected: tpl.category === 'rcbo' ? true : tpl.category === 'breaker',
      idrId: tpl.category === 'breaker' ? firstIdr?.id : undefined,
      lengthMeters: 15,
      powerFactor:
        tpl.category === 'breaker' || tpl.category === 'rcbo'
          ? getDefaultPowerFactor(tpl.defaultName, tpl.circuitType)
          : undefined,
      groupingFactor: 1.0,
    };
  };

  // Drop catalog item onto specific rail & slot without overlapping existing modules
  const handleDropCatalogItem = (
    catalogKey: string,
    targetRail: RailId,
    targetSlot: number
  ) => {
    setConfig((prev) => {
      const newMod = createModuleFromCatalog(
        catalogKey,
        targetRail,
        targetSlot,
        prev.modules,
        prev.supplyType,
        prev.voltageSystem
      );
      if (!newMod) return prev;
      const maxSlots = getMaxSlotsForRail(targetRail, prev);
      const placedModules = placeModuleWithoutOverlap(
        prev.modules,
        newMod,
        targetRail,
        targetSlot,
        maxSlots
      );
      setSelectedModuleId(newMod.id);
      const next: PanelConfig = {
        ...prev,
        modules: placedModules,
      };
      next.wires = syncWires(next, prev);
      return next;
    });
  };

  // Quick-add catalog item to first available rail/slot
  const handleQuickAddCatalogItem = (catalogKey: string) => {
    const tpl = CATALOG_ITEMS.find((c) => c.key === catalogKey);
    if (!tpl) return;

    setConfig((prev) => {
      let candidateRails: RailId[] = [];
      const isCircuit = tpl.category === 'breaker' || tpl.category === 'rcbo';
      if (prev.topology === 'fishbone') {
        if (isCircuit) {
          candidateRails = tpl.poles >= 2
            ? ['right_rail', 'left_rail']
            : ['left_rail', 'right_rail'];
        } else {
          candidateRails = ['top_main'];
        }
      } else {
        if (isCircuit) {
          candidateRails = (['row_2', 'row_3', 'row_4'] as RailId[]).slice(
            0,
            prev.horizontalRows - 1
          );
        } else {
          candidateRails = ['row_1'];
        }
      }

      let chosenRail: RailId | null = null;
      let chosenSlot: number | null = null;

      for (const rail of candidateRails) {
        const maxSlots = getMaxSlotsForRail(rail, prev);
        const slot = findFirstFreeSlot(rail, tpl.poles, prev.modules, maxSlots);
        if (slot !== null) {
          chosenRail = rail;
          chosenSlot = slot;
          break;
        }
      }

      if (chosenRail === null || chosenSlot === null) {
        alert(
          `Não há espaço disponível nos trilhos para adicionar este componente (${tpl.poles} polo${
            tpl.poles > 1 ? 's' : ''
          }).`
        );
        return prev;
      }

      const newMod = createModuleFromCatalog(
        catalogKey,
        chosenRail,
        chosenSlot,
        prev.modules,
        prev.supplyType,
        prev.voltageSystem
      );
      if (!newMod) return prev;
      const maxSlots = getMaxSlotsForRail(chosenRail, prev);
      const placedModules = placeModuleWithoutOverlap(
        prev.modules,
        newMod,
        chosenRail,
        chosenSlot,
        maxSlots
      );
      setSelectedModuleId(newMod.id);
      const next: PanelConfig = {
        ...prev,
        modules: placedModules,
      };
      next.wires = syncWires(next, prev);
      return next;
    });
    setMobileCatalogOpen(false);
  };

  // Update a specific module
  const handleUpdateModule = (id: string, partial: Partial<PanelModule>) => {
    setConfig((prev) => {
      const updatedModules = prev.modules.map((m) =>
        m.id === id ? { ...m, ...partial } : m
      );
      const next: PanelConfig = { ...prev, modules: updatedModules };
      if (partial.phases || partial.poles || partial.railId || partial.position !== undefined) {
        next.wires = syncWires(next, prev);
      }
      return next;
    });
  };

  // Toggle ON/OFF switch on a breaker
  const handleToggleModulePower = (id: string) => {
    setConfig((prev) => ({
      ...prev,
      modules: prev.modules.map((m) =>
        m.id === id ? { ...m, isOn: !m.isOn } : m
      ),
    }));
  };

  // Move module to another rail/slot with automatic collision avoidance
  const handleMoveModule = (
    moduleId: string,
    targetRail: RailId,
    targetSlot: number
  ) => {
    setConfig((prev) => {
      const moving = prev.modules.find((m) => m.id === moduleId);
      if (!moving) return prev;
      const maxSlots = getMaxSlotsForRail(targetRail, prev);
      const placedModules = placeModuleWithoutOverlap(
        prev.modules,
        moving,
        targetRail,
        targetSlot,
        maxSlots
      );
      const next: PanelConfig = { ...prev, modules: placedModules };
      next.wires = syncWires(next, prev);
      return next;
    });
  };

  // Nudge module slot left/right (or up/down on vertical rail)
  const handleNudgeModule = (id: string, delta: number) => {
    const mod = config.modules.find((m) => m.id === id);
    if (!mod) return;
    handleMoveModule(id, mod.railId, Math.max(0, mod.position + delta));
  };

  // Duplicate module
  const handleDuplicateModule = (id: string) => {
    setConfig((prev) => {
      const orig = prev.modules.find((m) => m.id === id);
      if (!orig) return prev;
      const maxSlots = getMaxSlotsForRail(orig.railId, prev);
      const slot = findFirstFreeSlot(orig.railId, orig.poles, prev.modules, maxSlots);
      if (slot === null) {
        alert('Não há espaço no trilho para duplicar este componente.');
        return prev;
      }
      const isCircuit = isLoadCircuit(orig);
      const maxCkt = prev.modules
        .filter(isLoadCircuit)
        .reduce((max, m) => Math.max(max, m.circuitNumber || 0), 0);

      const copy: PanelModule = {
        ...orig,
        id: `mod-${Date.now()}`,
        name: isCircuit
          ? `${orig.name} ${maxCkt + 1}`.trim()
          : orig.name,
        circuitNumber: isCircuit ? maxCkt + 1 : undefined,
        position: slot,
      };
      const placed = placeModuleWithoutOverlap(
        prev.modules,
        copy,
        orig.railId,
        slot,
        maxSlots
      );
      setSelectedModuleId(copy.id);
      const next: PanelConfig = { ...prev, modules: placed };
      next.wires = syncWires(next, prev);
      return next;
    });
  };

  // Delete module and only remove wires connected to that specific module
  const handleDeleteModule = (id: string) => {
    setConfig((prev) => {
      const remainingModules = prev.modules.filter((m) => m.id !== id);
      const next: PanelConfig = {
        ...prev,
        modules: remainingModules,
        wires: prev.wires.filter((w) => w.fromId !== id && w.toId !== id),
      };
      next.wires = syncWires(next, prev);
      return next;
    });
    if (selectedModuleId === id) setSelectedModuleId(null);
  };

  // Open preview modal before balancing phases R/S/T
  const handleOpenBalancePreview = () => {
    const preview = previewPhaseBalanceChanges(config);
    setBalancePreview(preview);
  };

  // Confirm phase balance changes from modal
  const handleConfirmBalancePhases = () => {
    if (!balancePreview) return;
    setConfig((prev) => {
      const next = { ...prev, modules: balancePreview.proposedModules };
      // Update colors of any auto-generated wires while preserving manual wires
      const hadAutoWires = prev.wires.some((w) => w.isAutoGenerated);
      if (hadAutoWires) {
        next.wires = mergeAutoWithManualWires(next);
      }
      return next;
    });
    setBalancePreview(null);
  };

  // Open preview modal for recalculating breaker ratings and wire gauges per NBR 5410
  const handleOpenBreakerRecalculatePreview = () => {
    const preview = previewBreakerRecalculation(config);
    setBreakerPreview(preview);
  };

  // Confirm breaker recalculation changes from modal
  const handleConfirmBreakerRecalculate = () => {
    if (!breakerPreview) return;
    setConfig((prev) => {
      const next = { ...prev, modules: breakerPreview.proposedModules };
      const hadAutoWires = prev.wires.some((w) => w.isAutoGenerated);
      if (hadAutoWires) {
        next.wires = mergeAutoWithManualWires(next);
      }
      return next;
    });
    setBreakerPreview(null);
  };

  // Auto-dimension all circuits per NBR 5410 (supports breakers and RCBOs)
  const handleAutoDimensionAll = () => {
    setConfig((prev) => {
      const updated = prev.modules.map((m) => {
        if (!isLoadCircuit(m)) return m;
        const current = calculateCircuitCurrent(m);
        const ratingAmps = getRecommendedBreakerRating(current, m.circuitType);
        const wireGaugeMm2 = getRecommendedWireGauge(
          current,
          ratingAmps,
          m.circuitType,
          m.poles,
          {
            lengthMeters: m.lengthMeters,
            voltage: m.voltage,
            groupingFactor: m.groupingFactor,
          }
        );
        return { ...m, ratingAmps, wireGaugeMm2 };
      });
      const next = { ...prev, modules: updated };
      const hadAutoWires = prev.wires.some((w) => w.isAutoGenerated);
      if (hadAutoWires) {
        next.wires = mergeAutoWithManualWires(next);
      }
      return next;
    });
  };

  // Add manual wire
  const handleAddWire = (
    fromId: string,
    fromPort: string,
    toId: string,
    toPort: string
  ) => {
    setConfig((prev) => ({
      ...prev,
      wires: [
        ...prev.wires,
        {
          id: `wire-manual-${Date.now()}`,
          fromId,
          fromPort,
          toId,
          toPort,
          wireType: activeWireType,
          gaugeMm2: activeWireGauge,
          isAutoGenerated: false,
        },
      ],
    }));
  };

  // Delete wire
  const handleDeleteWire = (wireId: string) => {
    setConfig((prev) => ({
      ...prev,
      wires: prev.wires.filter((w) => w.id !== wireId),
    }));
  };

  // Export JSON
  const handleExportJson = () => {
    const blob = new Blob([JSON.stringify(config, null, 2)], {
      type: 'application/json',
    });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${config.id || 'qdc-projeto'}.json`;
    a.click();
    URL.revokeObjectURL(url);
  };

  // Import JSON with robust Zod validation and sanitization
  const handleImportJson = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    const reader = new FileReader();
    reader.onload = () => {
      try {
        const parsed = JSON.parse(reader.result as string);
        const validation = parsePanelConfig(parsed);

        if (!validation.success) {
          const previewErrors = validation.errors.slice(0, 8).join('\n• ');
          const remaining = validation.errors.length - 8;
          const moreSuffix = remaining > 0 ? `\n... e mais ${remaining} erro(s).` : '';
          alert(
            `Falha na validação do projeto QDC:\n\n• ${previewErrors}${moreSuffix}\n\nVerifique se o arquivo JSON possui uma estrutura de quadro válida.`
          );
          return;
        }

        setConfig(validation.data);
        setSelectedModuleId(null);
      } catch {
        alert('Erro ao processar o arquivo JSON. Certifique-se de que é um JSON válido.');
      }
    };
    reader.readAsText(file);
    // Reset input so same file can be reloaded if desired
    e.target.value = '';
  };

  // Export SVG Diagram
  const handleExportSvg = () => {
    if (!svgRef.current) return;
    const serializer = new XMLSerializer();
    const source = serializer.serializeToString(svgRef.current);
    const blob = new Blob([source], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `${config.id || 'qdc-diagrama'}.svg`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="flex flex-col h-[100dvh] w-full max-w-full overflow-hidden bg-slate-950 text-slate-100 relative">
      {/* Top Application Header */}
      <header className="h-14 px-3 sm:px-4 bg-slate-900 border-b border-slate-800 flex items-center justify-between gap-2 sm:gap-4 shrink-0 print:hidden relative z-30">
        {/* Brand & Project Title */}
        <div className="flex items-center gap-2 sm:gap-3 min-w-0">
          <div className="w-8 h-8 sm:w-9 sm:h-9 rounded-lg bg-gradient-to-br from-amber-400 to-orange-600 flex items-center justify-center text-slate-950 shadow-md shrink-0">
            <Zap className="w-4 h-4 sm:w-5 sm:h-5 fill-current" />
          </div>
          <div className="min-w-0">
            <div className="flex items-center gap-1.5 sm:gap-2">
              <span className="font-extrabold tracking-tight text-xs sm:text-sm text-amber-400 shrink-0">
                QDC STUDIO
              </span>
              <span className="text-slate-600 hidden xs:inline">•</span>
              <input
                type="text"
                value={config.title}
                onChange={(e) => handleUpdateConfig({ title: e.target.value })}
                className="bg-transparent hover:bg-slate-800/70 focus:bg-slate-800 px-1.5 py-0.5 rounded text-xs sm:text-sm font-semibold text-slate-100 focus:outline-none w-28 xs:w-44 sm:w-60 truncate"
              />
            </div>
            <div className="text-[10px] sm:text-[11px] text-slate-400 truncate hidden md:block">
              Planejador de Quadro Elétrico e Dimensionamento NBR 5410
            </div>
          </div>
        </div>

        {/* Center Navigation Tabs (Desktop: >= md) */}
        <div className="hidden md:flex items-center bg-slate-950 p-1 rounded-lg border border-slate-800">
          <button
            onClick={() => setActiveTab('canvas')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-medium transition ${
              activeTab === 'canvas'
                ? 'bg-amber-500 text-slate-950 font-bold shadow'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            <LayoutGrid className="w-3.5 h-3.5" />
            Montagem do Quadro
          </button>
          <button
            onClick={() => setActiveTab('unifilar')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-medium transition ${
              activeTab === 'unifilar'
                ? 'bg-amber-500 text-slate-950 font-bold shadow'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            <Workflow className="w-3.5 h-3.5" />
            Diagrama Unifilar
          </button>
          <button
            onClick={() => setActiveTab('schedule')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-medium transition ${
              activeTab === 'schedule'
                ? 'bg-amber-500 text-slate-950 font-bold shadow'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            <FileSpreadsheet className="w-3.5 h-3.5" />
            Quadro de Cargas
          </button>
          <button
            onClick={() => setActiveTab('bom')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-md text-xs font-medium transition ${
              activeTab === 'bom'
                ? 'bg-amber-500 text-slate-950 font-bold shadow'
                : 'text-slate-400 hover:text-slate-200'
            }`}
          >
            <Printer className="w-3.5 h-3.5" />
            Materiais e Etiquetas
          </button>
        </div>

        {/* Right Model Switcher (Only Espinha de Peixe vs DIN Horizontal) & Actions (Desktop: >= md) */}
        <div className="hidden md:flex items-center gap-2 shrink-0">
          <div className="flex items-center bg-slate-950 p-1 rounded-lg border border-slate-800">
            <button
              onClick={() => handleSwitchTopology('fishbone')}
              className={`px-2.5 py-1 rounded text-xs font-medium transition ${
                config.topology === 'fishbone'
                  ? 'bg-slate-800 text-amber-400 font-semibold'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              Espinha de Peixe
            </button>
            <button
              onClick={() => handleSwitchTopology('horizontal')}
              className={`px-2.5 py-1 rounded text-xs font-medium transition ${
                config.topology === 'horizontal'
                  ? 'bg-slate-800 text-amber-400 font-semibold'
                  : 'text-slate-400 hover:text-slate-200'
              }`}
            >
              DIN Horizontal
            </button>
          </div>

          <button
            onClick={handleResetToDefaultModel}
            className="p-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300"
            title="Restaurar modelo padrão"
          >
            <RotateCcw className="w-4 h-4" />
          </button>

          <button
            onClick={handleClearPanel}
            className="p-1.5 rounded-lg bg-slate-800 hover:bg-rose-500/20 text-slate-300 hover:text-rose-300"
            title="Limpar todos os componentes do quadro"
          >
            <Trash2 className="w-4 h-4" />
          </button>

          <input
            ref={fileInputRef}
            type="file"
            accept=".json"
            onChange={handleImportJson}
            className="hidden"
          />
          <button
            onClick={() => fileInputRef.current?.click()}
            className="flex items-center gap-1 px-2.5 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium"
            title="Abrir projeto salvo"
          >
            <FolderOpen className="w-3.5 h-3.5" />
            Abrir
          </button>
        </div>

        {/* Mobile Header Hamburger Button (< md) */}
        <div className="flex md:hidden items-center gap-1 shrink-0">
          <button
            onClick={() => setMobileMenuOpen((v) => !v)}
            className="w-9 h-9 min-w-[36px] min-h-[36px] flex items-center justify-center rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white transition active:scale-95"
            aria-label="Opções do projeto"
            title="Menu de opções"
          >
            {mobileMenuOpen ? <X className="w-5 h-5" /> : <Menu className="w-5 h-5" />}
          </button>
        </div>
      </header>

      {/* Mobile Secondary Menu Dropdown Modal */}
      {mobileMenuOpen && (
        <div className="md:hidden fixed inset-0 z-50 bg-slate-950/80 backdrop-blur-sm flex flex-col justify-start pt-16 px-4 animate-in fade-in duration-150">
          <div
            className="fixed inset-0"
            onClick={() => setMobileMenuOpen(false)}
            aria-hidden="true"
          />
          <div className="relative bg-slate-900 border border-slate-800 rounded-2xl p-4 shadow-2xl space-y-4 max-w-sm w-full mx-auto z-10">
            <div className="flex items-center justify-between pb-2 border-b border-slate-800">
              <span className="text-xs font-bold uppercase tracking-wider text-slate-300">
                Opções do Projeto
              </span>
              <button
                onClick={() => setMobileMenuOpen(false)}
                className="w-8 h-8 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 flex items-center justify-center"
                aria-label="Fechar menu"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            <div>
              <label className="block text-xs text-slate-400 mb-1.5 font-medium">
                Modelo do Barramento
              </label>
              <div className="grid grid-cols-2 gap-1.5 bg-slate-950 p-1 rounded-lg border border-slate-800">
                <button
                  onClick={() => {
                    handleSwitchTopology('fishbone');
                    setMobileMenuOpen(false);
                  }}
                  className={`px-2.5 py-2 min-h-[40px] rounded text-xs font-medium transition text-center flex items-center justify-center ${
                    config.topology === 'fishbone'
                      ? 'bg-amber-500 text-slate-950 font-bold shadow'
                      : 'text-slate-400 hover:text-slate-200'
                  }`}
                >
                  Espinha de Peixe
                </button>
                <button
                  onClick={() => {
                    handleSwitchTopology('horizontal');
                    setMobileMenuOpen(false);
                  }}
                  className={`px-2.5 py-2 min-h-[40px] rounded text-xs font-medium transition text-center flex items-center justify-center ${
                    config.topology === 'horizontal'
                      ? 'bg-amber-500 text-slate-950 font-bold shadow'
                      : 'text-slate-400 hover:text-slate-200'
                  }`}
                >
                  DIN Horizontal
                </button>
              </div>
            </div>

            <div className="space-y-2 pt-2 border-t border-slate-800">
              <button
                onClick={() => {
                  fileInputRef.current?.click();
                  setMobileMenuOpen(false);
                }}
                className="w-full flex items-center gap-2.5 px-3 py-2.5 min-h-[42px] rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium"
              >
                <FolderOpen className="w-4 h-4 text-sky-400" />
                <span>Abrir Projeto JSON</span>
              </button>

              <button
                onClick={() => {
                  handleResetToDefaultModel();
                  setMobileMenuOpen(false);
                }}
                className="w-full flex items-center gap-2.5 px-3 py-2.5 min-h-[42px] rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-medium"
              >
                <RotateCcw className="w-4 h-4 text-amber-400" />
                <span>Restaurar Modelo Padrão</span>
              </button>

              <button
                onClick={() => {
                  handleClearPanel();
                  setMobileMenuOpen(false);
                }}
                className="w-full flex items-center gap-2.5 px-3 py-2.5 min-h-[42px] rounded-lg bg-rose-500/10 hover:bg-rose-500/20 text-rose-300 border border-rose-500/20 text-xs font-medium"
              >
                <Trash2 className="w-4 h-4 text-rose-400" />
                <span>Limpar Quadro</span>
              </button>
            </div>
          </div>
        </div>
      )}

      {/* Main Content Area */}
      <main className="flex-1 flex overflow-hidden pb-16 md:pb-0 relative">
        <ErrorBoundary>
          <div className={`flex-1 flex overflow-hidden ${activeTab === 'canvas' ? '' : 'hidden'}`}>
            {/* Desktop Catalog Sidebar (>= 1024px) */}
            <div className="hidden lg:flex shrink-0 h-full">
              <CatalogSidebar
                config={config}
                onUpdateConfig={handleUpdateConfig}
                onQuickAddCatalogItem={handleQuickAddCatalogItem}
                onAutoWire={handleAutoWire}
                onClearWires={handleClearWires}
                wireToolActive={wireToolActive}
                onToggleWireTool={() => setWireToolActive((v) => !v)}
                activeWireType={activeWireType}
                onSelectWireType={setActiveWireType}
                activeWireGauge={activeWireGauge}
                onSelectWireGauge={setActiveWireGauge}
              />
            </div>

            {/* Canvas Viewport (takes full width in mobile < 1024px) */}
            <div className="flex-1 w-full overflow-hidden relative flex flex-col">
              <PanelCanvas
                config={config}
                selectedModuleId={selectedModuleId}
                onSelectModule={handleSelectModule}
                onToggleModulePower={handleToggleModulePower}
                onMoveModule={handleMoveModule}
                onDropCatalogItem={handleDropCatalogItem}
                onDeleteModule={handleDeleteModule}
                onOpenCatalog={() => setMobileCatalogOpen(true)}
                onOpenInspector={() => setMobileInspectorOpen(true)}
                wireToolActive={wireToolActive}
                activeWireType={activeWireType}
                activeWireGauge={activeWireGauge}
                onAddWire={handleAddWire}
                onDeleteWire={handleDeleteWire}
                svgRef={svgRef}
              />
            </div>

            {/* Desktop Inspector Panel (>= 1024px) */}
            <div className="hidden lg:flex shrink-0 h-full">
              <InspectorPanel
                config={config}
                selectedModule={selectedModule}
                onUpdateModule={handleUpdateModule}
                onMoveModule={handleMoveModule}
                onDeleteModule={handleDeleteModule}
                onDuplicateModule={handleDuplicateModule}
                onNudgeModule={handleNudgeModule}
                onSelectModule={handleSelectModule}
                onOpenBalancePreview={handleOpenBalancePreview}
                onOpenBreakerRecalculatePreview={handleAutoDimensionAll}
              />
            </div>
          </div>

          {activeTab === 'unifilar' && (
            <SingleLineDiagramView config={config} />
          )}

          {activeTab === 'schedule' && (
            <CircuitScheduleView
              config={config}
              onUpdateModule={handleUpdateModule}
              onDeleteModule={handleDeleteModule}
              onQuickAddCircuit={() => handleQuickAddCatalogItem('brk_1p_16')}
              onQuickAddRcbo={() => handleQuickAddCatalogItem('rcbo_1p_16')}
              onOpenBalancePreview={handleOpenBalancePreview}
              onAutoDimensionAll={handleAutoDimensionAll}
              onOpenBreakerRecalculatePreview={handleOpenBreakerRecalculatePreview}
            />
          )}

          {activeTab === 'bom' && (
            <BomAndLabelsView
              config={config}
              onExportJson={handleExportJson}
              onExportSvg={handleExportSvg}
              onOpenUnifilar={() => setActiveTab('unifilar')}
            />
          )}
        </ErrorBoundary>
      </main>

      {/* Mobile Drawer: Catalog Sidebar (< 1024px) */}
      {mobileCatalogOpen && (
        <div className="lg:hidden fixed inset-0 z-50 flex">
          <div
            className="fixed inset-0 bg-slate-950/80 backdrop-blur-sm transition-opacity"
            onClick={() => setMobileCatalogOpen(false)}
            aria-hidden="true"
          />
          <div className="relative w-80 max-w-[85vw] h-full bg-slate-900 shadow-2xl flex flex-col z-10 animate-in slide-in-from-left duration-200 border-r border-slate-800">
            <CatalogSidebar
              config={config}
              onUpdateConfig={handleUpdateConfig}
              onQuickAddCatalogItem={handleQuickAddCatalogItem}
              onAutoWire={handleAutoWire}
              onClearWires={handleClearWires}
              wireToolActive={wireToolActive}
              onToggleWireTool={() => setWireToolActive((v) => !v)}
              activeWireType={activeWireType}
              onSelectWireType={setActiveWireType}
              activeWireGauge={activeWireGauge}
              onSelectWireGauge={setActiveWireGauge}
              onClose={() => setMobileCatalogOpen(false)}
            />
          </div>
        </div>
      )}

      {/* Mobile Drawer: Inspector Panel (< 1024px) */}
      {mobileInspectorOpen && (
        <div className="lg:hidden fixed inset-0 z-50 flex justify-end">
          <div
            className="fixed inset-0 bg-slate-950/80 backdrop-blur-sm transition-opacity"
            onClick={() => setMobileInspectorOpen(false)}
            aria-hidden="true"
          />
          <div className="relative w-80 max-w-[85vw] h-full bg-slate-900 shadow-2xl flex flex-col z-10 animate-in slide-in-from-right duration-200 border-l border-slate-800">
            <InspectorPanel
              config={config}
              selectedModule={selectedModule}
              onUpdateModule={handleUpdateModule}
              onMoveModule={handleMoveModule}
              onDeleteModule={handleDeleteModule}
              onDuplicateModule={handleDuplicateModule}
              onNudgeModule={handleNudgeModule}
              onSelectModule={handleSelectModule}
              onOpenBalancePreview={handleOpenBalancePreview}
              onOpenBreakerRecalculatePreview={handleAutoDimensionAll}
              onClose={() => setMobileInspectorOpen(false)}
            />
          </div>
        </div>
      )}

      {/* Mobile Bottom Navigation Bar (< md / 768px) */}
      <nav
        aria-label="Navegação Principal"
        className="fixed bottom-0 left-0 right-0 z-40 bg-slate-900/95 backdrop-blur border-t border-slate-800 grid grid-cols-4 py-1.5 md:hidden px-1 shadow-2xl"
      >
        <button
          onClick={() => setActiveTab('canvas')}
          className={`flex flex-col items-center justify-center flex-1 py-1 rounded-lg min-h-[44px] transition ${
            activeTab === 'canvas'
              ? 'text-amber-400 font-bold'
              : 'text-slate-400 hover:text-slate-200'
          }`}
        >
          <LayoutGrid className="w-5 h-5 mb-0.5" />
          <span className="text-[10px]">Montagem</span>
        </button>

        <button
          onClick={() => setActiveTab('unifilar')}
          className={`flex flex-col items-center justify-center flex-1 py-1 rounded-lg min-h-[44px] transition ${
            activeTab === 'unifilar'
              ? 'text-amber-400 font-bold'
              : 'text-slate-400 hover:text-slate-200'
          }`}
        >
          <Workflow className="w-5 h-5 mb-0.5" />
          <span className="text-[10px]">Unifilar</span>
        </button>

        <button
          onClick={() => setActiveTab('schedule')}
          className={`flex flex-col items-center justify-center flex-1 py-1 rounded-lg min-h-[44px] transition ${
            activeTab === 'schedule'
              ? 'text-amber-400 font-bold'
              : 'text-slate-400 hover:text-slate-200'
          }`}
        >
          <FileSpreadsheet className="w-5 h-5 mb-0.5" />
          <span className="text-[10px]">Cargas</span>
        </button>

        <button
          onClick={() => setActiveTab('bom')}
          className={`flex flex-col items-center justify-center flex-1 py-1 rounded-lg min-h-[44px] transition ${
            activeTab === 'bom'
              ? 'text-amber-400 font-bold'
              : 'text-slate-400 hover:text-slate-200'
          }`}
        >
          <Printer className="w-5 h-5 mb-0.5" />
          <span className="text-[10px]">Materiais</span>
        </button>
      </nav>

      {/* Phase Balance Preview Popup Modal */}
      {balancePreview && (
        <PhaseBalanceModal
          preview={balancePreview}
          supplyType={config.supplyType}
          maxRefAmps={
            config.modules.find((m) => m.category === 'main_breaker')
              ?.ratingAmps || 63
          }
          onConfirm={handleConfirmBalancePhases}
          onCancel={() => setBalancePreview(null)}
        />
      )}

      {/* Breaker Recalculation Preview Popup Modal */}
      {breakerPreview && (
        <BreakerRecalculateModal
          preview={breakerPreview}
          onConfirm={handleConfirmBreakerRecalculate}
          onCancel={() => setBreakerPreview(null)}
        />
      )}
    </div>
  );
}

export default App;
