export type LayoutTopology = 'fishbone' | 'horizontal';

export type SupplyType = 'mono' | 'bi' | 'tri'; // 1-phase, 2-phase, 3-phase
export type VoltageSystem = '127_220' | '220_380';
export type GroundingSystem = 'TN-S' | 'TN-C-S' | 'TN-C' | 'TT' | 'IT';

export type ComponentCategory =
  | 'main_breaker'
  | 'idr'
  | 'dps'
  | 'breaker';

export type PhaseAssignment = 'R' | 'S' | 'T' | 'RS' | 'RT' | 'ST' | 'RST' | 'N' | 'PE';

export type CircuitType = 'lighting' | 'tug' | 'tue' | 'protection';

export type CurveType = 'B' | 'C' | 'D';

export type WireType = 'phase_r' | 'phase_s' | 'phase_t' | 'neutral' | 'ground';

export type RailId =
  | 'top_main'     // For fishbone top DIN rail
  | 'left_rail'    // For fishbone left vertical rail
  | 'right_rail'   // For fishbone right vertical rail
  | 'row_1'        // For horizontal row 1 (top)
  | 'row_2'        // For horizontal row 2 (middle)
  | 'row_3'        // For horizontal row 3 (bottom)
  | 'row_4';       // Optional 4th horizontal row

export interface PanelModule {
  id: string;
  category: ComponentCategory;
  name: string;               // e.g. "Chuveiro Suíte", "Disjuntor Geral"
  circuitNumber?: number;     // e.g. 1, 2, 3...
  room?: string;              // e.g. "Cozinha", "Suíte", "Sala"
  circuitType: CircuitType;
  poles: 1 | 2 | 3 | 4;
  ratingAmps: number;         // e.g. 10, 16, 20, 25, 32, 40, 50, 63
  curve?: CurveType;          // B, C, D for breakers
  sensitivityMa?: number;     // 30mA for IDR
  dpsKa?: number;             // 20kA, 45kA for DPS
  dpsVoltage?: number;        // 275V, 175V
  railId: RailId;
  position: number;           // 0-based module slot index on the rail
  phases: PhaseAssignment;    // e.g. 'R', 'S', 'T', 'RS', 'RST'
  voltage: 127 | 220 | 380;
  powerWatts: number;         // Load in Watts (e.g. 5500W, 1200W)
  wireGaugeMm2: number;       // 1.5, 2.5, 4, 6, 10, 16, 25
  isOn: boolean;              // Interactive switch state in simulator
  drProtected?: boolean;      // Connected under IDR protection
  notes?: string;
}

export interface WireConnection {
  id: string;
  fromId: string;             // Module ID or bar ID ('neutral_bar', 'ground_bar', 'fishbone_bus')
  fromPort: string;           // e.g. 'out_0', 'in_0', 'term_3'
  toId: string;
  toPort: string;
  wireType: WireType;
  gaugeMm2: number;
  customColor?: string;
  label?: string;
  isAutoGenerated?: boolean;
}

export interface CombBusbarConfig {
  id: string;
  railId: RailId;
  type: 'mono' | 'bi' | 'tri';
  startSlot: number;
  endSlot: number;
  hasGenericConnectors: boolean;
}

export interface PanelConfig {
  id: string;
  title: string;
  subtitle: string;
  topology: LayoutTopology;
  supplyType: SupplyType;
  voltageSystem: VoltageSystem;
  groundingSystem: GroundingSystem;
  fishboneSlotsPerSide: number;
  horizontalRows: number;
  modulesPerRow: number;
  wireRoutingStyle: 'bundled' | 'curved';
  showWires: boolean;
  wireFilter: 'all' | 'phases' | 'neutral' | 'ground';
  phaseColorScheme: 'nbr_modern' | 'classic_br';
  modules: PanelModule[];
  wires: WireConnection[];
  combBusbars: CombBusbarConfig[];
}

export interface PortCoordinate {
  id: string;         // unique key: `${ownerId}:${portName}`
  ownerId: string;
  portName: string;
  label: string;
  x: number;
  y: number;
  direction?: 'up' | 'down' | 'left' | 'right';
  defaultWireType?: WireType;
}
